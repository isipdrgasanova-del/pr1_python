const CAT_LABELS = { builds: ' Гайды', lore: ' Лор', leaks: ' Сливы', casual: ' Казуал' }; //Создается неизменяемый объект-словарь CAT_LABELS. Он связывает технические названия категорий, нужен чтобы не писать проверки иф елс
let interests = { builds: 0, lore: 0, leaks: 0, casual: 0 }; //счетчик,который хранит цифровой след пользователя

function init() { //запускает приложение при первом входе
    renderStats(); //показывает прогресс в боковой панели
    renderFeed(); //сортирует фильтрует и выводит первые 10 новостей в ленте на экран
}

function renderStats() { 
    const box = document.getElementById('statsBox'); //программа ищет в документ хтмл элемент где айди равен статс бокс и сохраняет сслыку в переменную бокс
    if (!box) return; //не бокс, если на странице не найден бокс, то команда ретун останавливает функции,чтобы не было ошибки в коде
    box.innerHTML = ''; //отвечает за содержимое внутри хтмл и присваивает путсую строку
    
    const maxVal = Math.max(...Object.values(interests), 5); //нахрдим максимально кол-во очков чтобы настроить масштаб полосок
    let isTrapped = false; //пользователь не затсрял в информационном пузыре поэтому фолс

    for (let key in interests) { //берет по очереди каждую категори
        const val = interests[key]; //записывает в переменную точное кол-во очков для текущей категории
        const pct = Math.min((val / maxVal) * 100, 100); //здесь мы делим очки текущей темы на макимальные очки темы вал и умножаем на сто, функция маф мин страхует код чтобы он не стал больше 100 проц
        if (val >= 15) isTrapped = true; //если очков больше то мы меняем на истину, инфо пузырь набрался

        box.innerHTML += ` 
            <div class="stat-row">
                <div class="stat-info">
                    <span>${CAT_LABELS[key]}</span>
                    <span>${val} pt</span>
                </div>
                <div class="progress-track">
                    <div class="progress-bar ${key}" style="width: ${pct}%;"></div>
                </div>
            </div>
        `;
    }
    document.getElementById('alertBox').style.display = isTrapped ? 'block' : 'none'; //если пузырь равен тру, то стиль отображения меняется на блок, если фолс нон
}

function renderFeed() { //фильтрация и вывод новостей
    const box = document.getElementById('feedBox');
    if (!box) return; 
    box.innerHTML = ''; //полностью очищает контейнер перед тем сгенерить новые

    let feed = [...NEWS].sort((a, b) => (interests[b.cat] || 0) - (interests[a.cat] || 0)); //делает копию моего списка нововтсей 

    if (interests.leaks >= 15) feed = feed.filter(n => n.cat !== 'casual'); //если сливы набрали 15 очков, то выкидываем то что равно кажуал
    if (interests.casual >= 15) feed = feed.filter(n => n.cat !== 'leaks');
    if (interests.builds >= 15) feed = feed.filter(n => n.cat !== 'lore');
    if (interests.lore >= 15) feed = feed.filter(n => n.cat !== 'builds');

    const topItems = feed.slice(0, 10); //отрезает новости 10, берем 10 новостей и каждую строчку в хтмл

    box.innerHTML = topItems.map(n => ` 
        <div class="card ${n.cat}"> 
            <span class="card-tag">${CAT_LABELS[n.cat]}</span>
            <h4 class="card-title">${n.title}</h4>
            <div class="card-actions">
                <button class="btn btn-primary" onclick="interact('${n.cat}', 'like')"> Лайк</button>
                <button class="btn btn-secondary" onclick="interact('${n.cat}', 'skip')">⏭ Пропустить</button>
            </div>
        </div>
    `).join('');
}

function interact(cat, act) { //принимает два параметра
    if (act === 'like') {
        interests[cat] += 5; //прибавляем пять очков
    } else {
        interests[cat] = Math.max(interests[cat] - 2, 0); //иначе берем очки и вычитаем два
    }
    renderStats(); //пересчет в боковой панели
    renderFeed(); //люббимая тема вврех пропущ вниз
}

function resetAlgo() { //очитска пузыря
    interests = { builds: 0, lore: 0, leaks: 0, casual: 0 }; //стираем очки
    init(); //заново перезапустит приложение
}

document.addEventListener('DOMContentLoaded', init); //страница начинает слушать события сгнал что он прочтал файл от браузера и вызов функции инит